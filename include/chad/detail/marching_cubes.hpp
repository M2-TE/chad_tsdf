    // quick and dirty std::inplace_vector replica, since most compilers cant use c++26 yet
    template<typename T, std::size_t CAPACITY>
    struct inplace_vector {
        constexpr inplace_vector(std::initializer_list<T> ilist): _data{}, _size{ ilist.size() } {
            T* write_p = _data;
            for (auto read_it = ilist.begin(); read_it != ilist.end(); read_it++, write_p++) {
                *write_p = *read_it;
            }
        }
        auto inline operator[](std::size_t index) const -> const T& {
            return _data[index];
        }
        auto inline size() const -> std::size_t {
            return _size;
        }
        auto inline data() const -> T* {
            return _data.data();
        }

        private:
        T _data[CAPACITY];
        std::size_t _size;
    };

